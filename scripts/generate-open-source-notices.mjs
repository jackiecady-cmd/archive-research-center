import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function walk(dir, found = []) {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === "dist" || name.startsWith(".")) continue;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full, found);
    else if (name === "package.json") found.push(full);
  }
  return found;
}

const packages = new Map();
for (const file of walk(root)) {
  const manifest = JSON.parse(readFileSync(file, "utf8"));
  for (const field of ["dependencies", "devDependencies"]) {
    const deps = manifest[field] ?? {};
    for (const [name, version] of Object.entries(deps)) {
      if (name.startsWith("@workspace/")) continue;
      const listed = packages.get(name) ?? new Set();
      listed.add(String(version));
      packages.set(name, listed);
    }
  }
}

const lines = [
  "# Open source notices",
  "",
  "This page is a stub. It lists direct npm dependencies declared in this repository and the fonts the site requests. It is not a complete transitive licence audit.",
  "",
  "## Fonts",
  "",
  "- Inter, SIL Open Font License",
  "- Playfair Display, SIL Open Font License",
  "",
  "The site currently loads both families from Google Fonts (`fonts.googleapis.com` and `fonts.gstatic.com`). The font software itself is under the SIL Open Font License.",
  "",
  "## npm dependencies",
  "",
  "Generated by `node scripts/generate-open-source-notices.mjs` from workspace `package.json` files. Workspace packages are omitted.",
  "",
];

for (const name of [...packages.keys()].sort((a, b) => a.localeCompare(b))) {
  const versions = [...packages.get(name)].sort().join(", ");
  lines.push(`- ${name} (${versions})`);
}
lines.push("");

const out = path.join(root, "legal/open-source-notices.md");
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${packages.size} dependencies to ${path.relative(root, out)}`);
